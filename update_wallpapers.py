"""Regenerate root wallpapers.js from images in the wallpapers/ directory.

Run: python update_wallpapers.py
Windows uses System.Drawing without extra dependencies. Other platforms, or
formats unsupported by System.Drawing, require Pillow: python -m pip install Pillow
"""

import json
import math
import os
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import quote


DIRECTORY = Path(__file__).resolve().parent
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".bmp", ".avif", ".tif", ".tiff"}

# Paths travel as JSON over stdin, never interpolated into shell commands.
WINDOWS_SAMPLER = r"""
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$paths = ConvertFrom-Json ([Console]::In.ReadToEnd())
$results = @()
foreach ($path in $paths) {
    $original = $null
    $bitmap = $null
    $graphics = $null
    try {
        $original = [System.Drawing.Image]::FromFile($path)
        $bitmap = New-Object System.Drawing.Bitmap 32,32
        $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
        $graphics.DrawImage($original, 0, 0, 32, 32)
        $pixels = @()
        for ($y = 0; $y -lt 32; $y++) {
            for ($x = 0; $x -lt 32; $x++) {
                $p = $bitmap.GetPixel($x, $y)
                $pixels += ,@([int]$p.R, [int]$p.G, [int]$p.B, [int]$p.A)
            }
        }
        $results += @{ pixels = $pixels }
    } catch {
        $results += @{ error = $_.Exception.Message }
    } finally {
        if ($graphics) { $graphics.Dispose() }
        if ($bitmap) { $bitmap.Dispose() }
        if ($original) { $original.Dispose() }
    }
}
ConvertTo-Json -InputObject @($results) -Depth 5 -Compress
"""


def natural_key(path):
    return [int(part) if part.isdigit() else part.casefold()
            for part in re.split(r"(\d+)", path.name)]


def sample_images(paths):
    try:
        from PIL import Image
    except ImportError:
        if os.name != "nt":
            raise RuntimeError("Install Pillow: python -m pip install Pillow") from None
        result = subprocess.run(
            ["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", WINDOWS_SAMPLER],
            input=json.dumps([str(path) for path in paths]),
            capture_output=True, text=True, check=True,
        )
        samples = json.loads(result.stdout)
        if len(samples) != len(paths):
            raise RuntimeError("Image sampler returned an incomplete result")
        for path, sample in zip(paths, samples):
            if "error" in sample:
                raise RuntimeError(f"Cannot read {path.name}. Try installing Pillow. {sample['error']}")
            yield sample["pixels"]
    else:
        for path in paths:
            with Image.open(path) as image:
                yield list(image.convert("RGBA").resize((32, 32)).get_flattened_data())


def extract_theme(pixels):
    """Choose a prevalent colour, then darken fill and lighten the border."""
    buckets = {}
    for red, green, blue, alpha in pixels:
        if alpha < 128:
            continue
        color = (red, green, blue)
        key = tuple(channel >> 5 for channel in color)
        bucket = buckets.setdefault(key, {"sum": [0, 0, 0], "count": 0, "weight": 0})
        largest, smallest = max(color), min(color)
        bucket["weight"] += 1 + ((largest - smallest) / largest if largest else 0)
        bucket["count"] += 1
        for index, channel in enumerate(color):
            bucket["sum"][index] += channel
    if not buckets:
        raise ValueError("Image contains no sufficiently opaque pixels")
    # Explicit tie-break keeps output stable across repeated runs.
    dominant = max(buckets.items(), key=lambda item: (item[1]["weight"], item[0]))[1]
    color = [channel / dominant["count"] for channel in dominant["sum"]]
    return {
        "fill": [math.floor(channel * .22 + 8 + .5) for channel in color],
        "border": [math.floor(channel * .45 + 255 * .55 + .5) for channel in color],
    }


def main():
    image_directory = DIRECTORY / "wallpapers"
    if not image_directory.is_dir():
        raise RuntimeError(f"Wallpaper directory not found: {image_directory}")
    paths = sorted((path for path in image_directory.iterdir()
                    if path.is_file() and path.suffix.lower() in EXTENSIONS), key=natural_key)
    entries = []
    if paths:
        for path, pixels in zip(paths, sample_images(paths)):
            entries.append({"key": path.name,
                            "source": quote(path.relative_to(DIRECTORY).as_posix()), "shade": .3,
                            "theme": extract_theme(pixels)})
    output = DIRECTORY / "wallpapers.js"
    contents = ("// Generated by update_wallpapers.py. Run it again after changing images.\n"
                "window.STARTPAGE_WALLPAPERS = " + json.dumps(entries, ensure_ascii=True, indent=2) + ";\n")
    # Only replace the existing list once every image has been processed successfully.
    temporary = output.with_suffix(".js.tmp")
    try:
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Updated {output.name}: {len(entries)} wallpapers.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"Update failed; existing wallpaper list was preserved: {error}", file=sys.stderr)
        sys.exit(1)
